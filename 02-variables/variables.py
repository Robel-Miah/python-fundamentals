# The same value converted to three different types
integer_value = int(30)    # 30
string_value  = str(30)     # "30" (text, not a number)
float_value   = float(30)    # 30.0

print(integer_value, string_value, float_value)

print(type(integer_value))
print(type(string_value))
print(type(float_value))
